-- Правила категоризации размножились: миграция 002 с сидом выполнялась при
-- каждом запуске приложения, пока не появился schema_migrations. В базе
-- оказалось 1650 записей вместо 30 — по 55 копий каждого правила.
--
-- Последствия были не только косметические: categorizeEvent() читает и
-- разбирает ВСЕ правила на каждую вставку события, то есть 1650 строк на
-- каждое событие вместо 30. И список правил в настройках был нечитаемым.
--
-- Оставляем по одной записи на (категория, поле, сравнение, значение).
DELETE FROM category_rules
WHERE id NOT IN (
  SELECT MIN(id)
  FROM category_rules
  GROUP BY category_id, field, match_type, value
);
